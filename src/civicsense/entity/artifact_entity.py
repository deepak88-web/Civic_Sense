
from dataclasses import dataclass
from pathlib import Path
from typing import Optional


@dataclass
class DataIngestionArtifact:
    """
    Stores the output paths generated by data ingestion.
    """

    supervised_data_file_path: Path
    prediction_data_file_path: Path


@dataclass
class DataValidationArtifact:
    """
    Stores the results of data validation.
    """

    validation_status: bool
    validation_message: str

    validated_supervised_file_path: Path
    validated_prediction_file_path: Path


@dataclass
class DataTransformationArtifact:
    """
    Stores the outputs generated during data transformation.
    """

    transformed_data_file_path: Path

    tokenizer_file_path: Path
    label_encoder_file_path: Path

    max_sequence_length_file_path: Path
    embedding_matrix_file_path: Path

    word2vec_model_file_path: Path


@dataclass
class ModelTrainerArtifact:
    """
    Stores the trained model and training history.
    """

    trained_model_file_path: Path
    training_history_file_path: Path


@dataclass
class ModelEvaluationArtifact:
    """
    Stores model evaluation results.
    """

    evaluation_status: bool

    metrics_file_path: Path
    classification_report_file_path: Path
    confusion_matrix_file_path: Path


@dataclass
class PredictionArtifact:
    """
    Stores batch prediction output information.
    """

    predictions_file_path: Path
    low_confidence_file_path: Path
    prediction_summary_file_path: Path

    total_predictions: int
    low_confidence_count: int



@dataclass
class BatchPredictionArtifact:

    predictions_file_path: Path
    low_confidence_file_path: Path
    prediction_summary_file_path: Path

    total_predictions: int
    low_confidence_count: int
